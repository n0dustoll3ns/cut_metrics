/// Решение пользователя по источнику данных для метрики — Фаза 6, часть B.
///
/// Ключ решения — пара (метрика, пакет приложения-источника). Хранится в
/// `SettingsService` (`src_decision.<metric>.<package>`); отсутствие ключа =
/// [none]. Новый источник без решения снова спрашивает «Ок / Не ок».
enum ConfirmDecision {
  /// Решения нет (источник новый или решение сброшено) — карточка крупно
  /// спрашивает «Ок / Не ок» (состояние `autoUnconfirmed`).
  none,

  /// «Ок» — источнику доверяем: карточка тихая (`autoConfirmed`), крупные
  /// кнопки не показываются. Пишет ТОЛЬКО решение, данные не пишет.
  confirmed,

  /// «Не ок» — источник отклонён для метрики: его точки исключаются из
  /// резолюции, каждый день — ручной ввод (состояние `sourceRefused`).
  refused,
}
