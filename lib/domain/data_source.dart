/// Источник данных записи.
///
/// Tier 1 (ручной ввод через Cut Metrics) всегда побеждает над Tier 2 (внешние
/// источники), если запись существует на дату — см. `HealthDataProcessor`.
enum DataSource {
  /// Tier 1 — запись, у которой `dataOrigin` = пакет нашего приложения
  /// (`com.example.cut_metrics`). Ручной ввод пользователя.
  manual,

  /// Tier 2 — любые внешние записи (умные весы, шагомер телефона, другие приложения).
  external,
}