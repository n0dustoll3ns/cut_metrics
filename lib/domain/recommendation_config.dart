/// Все настраиваемые константы Фазы 5 — в ОДНОМ месте.
///
/// Требование пользователя: «писать код так, чтобы это было зафиксировано в одном месте,
/// чтобы если что можно было быстро изменить» (ответ №3 при сборе требований, 2026-08-21).
///
/// Источник значений — `docs/phase5_ui_screens_and_activity_spec.md` §6
/// и `docs/phase5_recommendation_and_indicator_spec.md` (секция «Изменения»).
class RecommendationConfig {
  RecommendationConfig._();

  // ─── RecommendationEngine ─────────────────────────────────────────────────────

  /// Фиксированный период EMA движка рекомендаций.
  ///
  /// НЕ связан с `_emaPeriod` дашборда (который зависит от длины диапазона) —
  /// требование спеки Фазы 5, A.2.
  static const int engineEmaPeriod = 7;

  /// Допуск статуса «в темпе» в процентных пунктах (±0.15 п.п.).
  ///
  /// Подтверждён пользователем 2026-08-21 (закрытый вопрос A.4 исходной спеки).
  static const double paceTolerance = 0.15;

  /// Минимум сырых точек веса в 7-дневном окне для расчёта саммари.
  static const int minWeightPointsInWindow = 3;

  /// Дефолтный целевой темп, %/нед (до первого захода в настройки).
  static const double defaultTargetPacePercent = 0.8;

  /// Границы слайдера целевого темпа и шаг (Настройки).
  static const double sliderMin = 0.3;
  static const double sliderMax = 1.4;
  static const double sliderStep = 0.1;

  // ─── Активность / калории ─────────────────────────────────────────────────────

  /// Ккал на один шаг на 1 кг веса: `шаги × вес × 0.0005`.
  ///
  /// ≈400 ккал на 10 000 шагов при 80 кг — соответствует типичным оценкам трекеров.
  static const double stepsKcalPerKgPerStep = 0.0005;

  // ─── Диапазоны данных ─────────────────────────────────────────────────────────

  /// Максимальный диапазон Тренда («3 месяца»). Он же — объём предзагрузки в
  /// `DashboardViewModel.load` (движку рекомендаций нужен вес независимо от
  /// того, какой сегмент пользователь смотрит на Тренде).
  static const int maxTrendDays = 90;

  /// Диапазон графика на вкладке «Сегодня».
  static const int todayChartDays = 30;

  // ─── Тексты ───────────────────────────────────────────────────────────────────

  /// Снекбар при попытке открыть Саммари без достаточных данных.
  static const String summaryNotReadyMessage =
      'Недостаточно данных — нужно ≥3 взвешивания за неделю';

  /// Заголовок блока рекомендации на Саммари.
  static const String summaryRecLabel = 'Рекомендация на следующую неделю';

  /// Вывод-строка (conclusion) по статусам. {actual}/{target} подставляются движком.
  static const String conclusionInPace =
      'Вес снижается стабильно, в пределах целевого темпа.';
  static const String conclusionTooSlow =
      'Темп ниже целевого — вес снижается слишком медленно.';
  static const String conclusionTooFast =
      'Темп выше целевого диапазона — риск потери мышечной массы.';

  /// Тексты рекомендаций. {actual}/{target} подставляются движком (abs, 1 знак).
  static const String recInPace =
      'Темп {actual}%/нед при цели {target}%/нед. Оставь текущую калорийность без изменений.';
  static const String recTooSlow =
      'Темп {actual}%/нед ниже цели {target}%/нед. Снизь калорийность на ~100 ккал в сутки.';
  static const String recTooFast =
      'Темп {actual}%/нед выше цели {target}%/нед. Добавь ~150–200 ккал в сутки, чтобы вернуться в целевой темп.';
}
